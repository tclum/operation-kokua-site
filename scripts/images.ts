// Builds every file in public/images/ from the old site's uploads, so the step
// reruns. The jobs are in scripts/image-jobs.ts. Each output is EXIF-rotated,
// then written with ALL metadata stripped (no EXIF, XMP or IPTC), at 640 and
// 1100 pixels wide and never wider than its source. Files no job builds are
// removed, so public/images/ holds exactly the jobs' outputs.
// It also copies the IRS letter (job "irs-letter") to public/docs/ and writes
// docs/images.md from the jobs and the mirror's manifest.
// The only input is `source/weebly/`: gitignored and read-only, so this script
// reads from it and never writes to it.

import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { DOCS_OUT_DIR, type Job, MANIFEST, OUT_DIR, irsLetterJob, jobs } from "./image-jobs";

const ROOT = path.resolve(__dirname, "..");
const IMAGES_DOC = path.join(ROOT, "docs/images.md");

type ManifestRow = { bytes: string; sha256: string; pages: string; url: string };

function readManifest(): Map<string, ManifestRow> {
  const rows = new Map<string, ManifestRow>();
  for (const line of readFileSync(MANIFEST, "utf8").split("\n").slice(1)) {
    const [file, bytes, sha256, pages, url] = line.split("\t");
    if (file) rows.set(file, { bytes, sha256, pages, url });
  }
  return rows;
}

async function build(job: Job): Promise<string[]> {
  const meta = await sharp(job.source).metadata();
  const lines: string[] = [];
  for (const [i, size] of job.sizes.entries()) {
    const out = path.join(OUT_DIR, job.outputs[i]);
    // sharp drops all metadata by default; .rotate() with no argument applies
    // the EXIF orientation first. withoutEnlargement keeps us at or below the
    // source's own width.
    const info = await sharp(job.source)
      .rotate()
      .resize({ width: size, withoutEnlargement: true })
      .jpeg({ quality: job.quality, mozjpeg: true, progressive: true })
      .toFile(out);
    console.log(`${path.relative(ROOT, out)}  ${info.width}x${info.height}  ${info.size} bytes`);
    lines.push(`${job.outputs[i]} (${info.width}x${info.height})`);
  }
  return [`${meta.width}x${meta.height}`, ...lines];
}

function imagesDoc(rows: { job: Job; sourceSize: string; outputs: string[] }[], manifest: Map<string, ManifestRow>): string {
  const head = `# Images

Generated by \`pnpm images\` (\`scripts/images.ts\`, jobs in \`scripts/image-jobs.ts\`); do not edit by hand. Every file in \`public/images/\` is built from the upload named below in \`source/weebly/uploads/\` (the mirror of operationkokua.weebly.com taken 2026-11-24; gitignored, read-only): EXIF-rotated, then written with all metadata stripped, at 640 and 1100 pixels wide and never wider than the source. The sha256 is the upload's, from \`source/weebly/manifest.tsv\`.

Every photo here was published by Operation Kokua on its previous site; originals requested from David Mathews.

Photos left out of slice 1 (patients, surgery in progress, children, private contact details, or under 600 pixels) are listed in \`src/lib/excluded.ts\`; a test keeps them out.

| Output | Source | Source size | Used on (old-site page) | sha256 | Rights |
|---|---|---|---|---|---|
`;
  const body = rows
    .map(({ job, sourceSize, outputs }) => {
      const m = manifest.get(job.file);
      if (!m) throw new Error(`${job.file}: not in the manifest`);
      return `| ${outputs.map((o) => `\`public/images/${o}\``).join("<br>")} | \`${job.file}\` | ${sourceSize} | ${job.usedOn.join("; ")} | \`${m.sha256}\` | published by Operation Kokua on its previous site; originals requested from David Mathews |`;
    })
    .join("\n");
  const pdf = manifest.get("irs_approval_letter.pdf");
  if (!pdf) throw new Error("irs_approval_letter.pdf: not in the manifest");
  const docs = `

## Documents

| Output | Source | Used on | sha256 |
|---|---|---|---|
| \`public/docs/irs-approval-letter.pdf\` (job \`${irsLetterJob.name}\`, copied byte for byte) | \`irs_approval_letter.pdf\` (old page ${pdf.pages}) | /about, the legal line | \`${pdf.sha256}\` |
`;
  return head + body + docs;
}

async function main(): Promise<void> {
  mkdirSync(OUT_DIR, { recursive: true });
  mkdirSync(DOCS_OUT_DIR, { recursive: true });
  const manifest = readManifest();
  const rows: { job: Job; sourceSize: string; outputs: string[] }[] = [];
  for (const job of jobs) {
    if (!existsSync(job.source)) throw new Error(`missing source ${job.source}`);
    const [sourceSize, ...outputs] = await build(job);
    rows.push({ job, sourceSize, outputs });
  }
  // Remove anything no job builds (a photo dropped from the content).
  const expected = new Set(jobs.flatMap((j) => j.outputs));
  for (const f of readdirSync(OUT_DIR)) {
    if (!expected.has(f)) {
      rmSync(path.join(OUT_DIR, f));
      console.log(`removed public/images/${f} (no job builds it)`);
    }
  }
  copyFileSync(irsLetterJob.source, irsLetterJob.output);
  console.log(`${path.relative(ROOT, irsLetterJob.output)}  copied (job ${irsLetterJob.name})`);
  writeFileSync(IMAGES_DOC, imagesDoc(rows, manifest));
  console.log(`${path.relative(ROOT, IMAGES_DOC)}  written (${rows.length} photos)`);
  console.log(`${expected.size} image files from ${jobs.length} photos`);
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
